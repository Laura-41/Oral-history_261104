def E(
    entity_id: str,
    canonical_name: str,
    entity_type: str,
    entity_subtype: str,
    aliases: tuple[tuple[str, str], ...] = (),
    description: str = "",
    authority_status: str = "LOCAL_CANONICAL",
    confidence: str = "HIGH",
    review_status: str | None = None,
) -> dict:
    return {
        "entity_id": entity_id,
        "canonical_name": canonical_name,
        "entity_type": entity_type,
        "entity_subtype": entity_subtype,
        "aliases": [{"alias_text": text, "alias_type": kind} for text, kind in aliases],
        "description": description,
        "authority_status": authority_status,
        "confidence": confidence,
        "review_status": review_status or ("NEEDS_REVIEW" if authority_status in {"TRANSCRIPTION_UNCERTAIN", "UNRESOLVED"} else "MODEL_CANDIDATE"),
    }


